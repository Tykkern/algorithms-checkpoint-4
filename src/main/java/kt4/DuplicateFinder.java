package kt4;

/**
 * Задача 6. Повторяющееся число без изменения массива и с памятью O(1).
 */
public final class DuplicateFinder {

    private DuplicateFinder() {
    }

    /**
     * Смотрим на массив как на граф: из индекса i ведёт стрелка в индекс nums[i].
     * Индексов n + 1 (от 0 до n), значения от 1 до n, поэтому в индекс 0 стрелок
     * нет, и путь из 0 рано или поздно зацикливается. В узел, с которого начинается
     * цикл, входят две стрелки: из хвоста и из самого цикла. Это два разных индекса
     * с одинаковым значением, то есть искомое повторяющееся число.
     *
     * Вход в цикл ищем алгоритмом Флойда. Сначала медленный указатель (шаг 1)
     * и быстрый (шаг 2) встречаются внутри цикла. Потом один указатель
     * возвращаем в 0, и оба идут по одному шагу: встретятся они ровно на входе
     * в цикл. Массив не меняется, память O(1), время O(n).
     *
     * Бинарный поиск по значению тоже уложился бы в O(1) памяти, но за O(n log n).
     */
    public static int find(int[] nums) {
        int slow = nums[0];
        int fast = nums[nums[0]];
        while (slow != fast) {
            slow = nums[slow];
            fast = nums[nums[fast]];
        }

        slow = 0;
        while (slow != fast) {
            slow = nums[slow];
            fast = nums[fast];
        }
        return slow;
    }
}
